import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import sharp from "sharp";

const root = fileURLToPath(new URL("..", import.meta.url));
const icon = await readFile(path.join(root, "art/brand/mochlik-icon.png"));
const logo = await readFile(path.join(root, "art/brand/zhiv-logo.png"));
const output = path.join(root, "public");
await mkdir(path.join(output, "brand"), { recursive: true });

const files = new Map();
const pngOptions = { palette: true, quality: 100, effort: 10, compressionLevel: 9 };
for (const size of [32, 192, 512]) {
  files.set(`/icon-${size}.png`, await sharp(icon).resize(size, size).png(pngOptions).toBuffer());
}
files.set("/apple-touch-icon.png", await sharp(icon).resize(180, 180).png(pngOptions).toBuffer());

// The supplied full-bleed background already supports launcher masks. The
// recognizable face sits inside the central safe circle; decorative ear tips
// can be cropped by a launcher without an artificial frame around the artwork.
files.set("/icon-maskable-512.png", files.get("/icon-512.png"));
files.set("/brand/zhiv-logo.webp", await sharp(logo).resize(1024, 1024, { withoutEnlargement: true })
  .webp({ quality: 86, alphaQuality: 100, effort: 6 }).toBuffer());

// Keep this old address usable for installed clients with older document metadata.
files.set("/icon.svg", Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 192 192"><image width="192" height="192" href="data:image/png;base64,${files.get("/icon-192.png").toString("base64")}"/></svg>\n`));

const faviconSizes = [16, 32, 48];
const faviconImages = await Promise.all(faviconSizes.map(size => sharp(icon).resize(size, size).png(pngOptions).toBuffer()));
const faviconHeader = Buffer.alloc(6 + faviconSizes.length * 16);
faviconHeader.writeUInt16LE(1, 2);
faviconHeader.writeUInt16LE(faviconSizes.length, 4);
let offset = faviconHeader.length;
faviconImages.forEach((bytes, index) => {
  const entry = 6 + index * 16;
  faviconHeader.writeUInt8(faviconSizes[index], entry);
  faviconHeader.writeUInt8(faviconSizes[index], entry + 1);
  faviconHeader.writeUInt16LE(1, entry + 4);
  faviconHeader.writeUInt16LE(32, entry + 6);
  faviconHeader.writeUInt32LE(bytes.length, entry + 8);
  faviconHeader.writeUInt32LE(offset, entry + 12);
  offset += bytes.length;
});
files.set("/favicon.ico", Buffer.concat([faviconHeader, ...faviconImages]));

const urls = {};
for (const [name, bytes] of files) {
  const revision = createHash("sha256").update(bytes).digest("hex").slice(0, 12);
  urls[name] = `${name}?v=${revision}`;
  await writeFile(path.join(output, name), bytes);
  console.log(`${name}: ${(bytes.length / 1024).toFixed(1)} KiB`);
}

const constants = {
  BRAND_LOGO_SRC: urls["/brand/zhiv-logo.webp"],
  BRAND_ICON_32_SRC: urls["/icon-32.png"],
  BRAND_ICON_192_SRC: urls["/icon-192.png"],
  BRAND_ICON_512_SRC: urls["/icon-512.png"],
  BRAND_MASKABLE_ICON_SRC: urls["/icon-maskable-512.png"],
  BRAND_APPLE_ICON_SRC: urls["/apple-touch-icon.png"],
  BRAND_FAVICON_SRC: urls["/favicon.ico"],
};
await writeFile(path.join(root, "lib/brand-assets.ts"),
  "// Generated by scripts/prepare-brand-assets.mjs from the supplied art/brand masters.\n"
  + Object.entries(constants).map(([key, value]) => `export const ${key} = ${JSON.stringify(value)};`).join("\n") + "\n");
