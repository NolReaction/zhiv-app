function normalizeSearch(value: string) {
  return value.toLocaleLowerCase("ru-RU").replaceAll("ё", "е").trim();
}

export function searchWorldHelp(topics: readonly WorldHelpTopic[], query: string): readonly WorldHelpTopic[] {
  const terms = normalizeSearch(query).split(/\s+/).filter(Boolean);
  if (!terms.length) return topics;
  return topics.filter(topic => {
    const text = normalizeSearch([topic.title, topic.summary, topic.keywords, ...(topic.paragraphs ?? []), ...(topic.steps ?? []), topic.note ?? ""].join(" "));
    return terms.every(term => text.includes(term));
  });
}
